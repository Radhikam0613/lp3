import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.preprocessing import StandardScaler
from sklearn.cluster import KMeans, AgglomerativeClustering
from sklearn.metrics import silhouette_score
from scipy.cluster.hierarchy import linkage, dendrogram

df = pd.read_csv("data.csv", encoding="latin1")

print(df.head())
print(df.shape)
print(df.isnull().sum())

features = ['SALES', 'QUANTITYORDERED', 'PRICEEACH', 'MSRP']

data = df[features].copy()
data = data.fillna(data.median())
data = data.drop_duplicates()

scaler = StandardScaler()
X = scaler.fit_transform(data)

print("Data shape:", X.shape)
print("Missing values:", data.isnull().sum().sum())

wcss = []
for k in range(1, 11):
    model = KMeans(n_clusters=k, random_state=42, n_init=10)
    model.fit(X)
    wcss.append(model.inertia_)
plt.plot(range(1, 11), wcss, marker='o')
plt.xlabel("Number of Clusters (K)")
plt.ylabel("WCSS")
plt.title("Elbow Method")
plt.show()

k = 3
km = KMeans(n_clusters=k, random_state=42, n_init=10)
data['KMeans_Cluster'] = km.fit_predict(X)
print(data['KMeans_Cluster'].value_counts().sort_index())
print(data.groupby('KMeans_Cluster')[features].mean().round(2))

plt.figure(figsize=(7, 5))
sns.scatterplot(
    x=X[:, 0], y=X[:, 2],
    hue=data['KMeans_Cluster'],
    palette='Set1'
)
plt.xlabel("Standardized Sales")
plt.ylabel("Standardized Price Each")
plt.title("K-Means Clusters")
plt.show()

print("K-Means silhouette:",
      round(silhouette_score(X, data['KMeans_Cluster']), 3))

